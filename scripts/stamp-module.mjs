#!/usr/bin/env node
/**
 * Write module/scripts/build-info.js: the content hash of module/ plus the git
 * commit it was stamped from. The module sends the hash in its hello, so the
 * server can tell a stale or hand-patched install from the real thing.
 *
 *   node scripts/stamp-module.mjs           re-stamp (no-op when the hash is unchanged)
 *   node scripts/stamp-module.mjs --check   exit 1 if the stamp is stale (CI)
 *
 * Run it after changing anything under module/, and commit build-info.js.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { BUILD_INFO_PATH, hashModuleTree } from "../server/lib/module-hash.js";

export const MODULE_DIR = fileURLToPath(new URL("../module", import.meta.url));

/** The stamp in `moduleDir`'s build-info.js, or null if missing/unparseable. */
export function readStamp(moduleDir) {
  try {
    const src = readFileSync(path.join(moduleDir, BUILD_INFO_PATH), "utf8");
    return JSON.parse(src.match(/BUILD_INFO = (\{.*\});/)[1]);
  } catch {
    return null;
  }
}

function gitCommit(cwd) {
  try {
    return execFileSync("git", ["rev-parse", "--short=12", "HEAD"], { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "unknown";
  }
}

/**
 * Re-stamp `moduleDir`. The file is left alone when the hash already matches,
 * so committing unrelated work does not churn the commit field.
 * @returns {{hash: string, commit: string, changed: boolean}}
 */
export function stampModule(moduleDir) {
  const hash = hashModuleTree(moduleDir);
  const old = readStamp(moduleDir);
  if (old?.hash === hash) return { ...old, changed: false };
  // ponytail: commit is HEAD at stamp time, i.e. the parent of the commit that
  // will carry this stamp. Good enough to locate the build; the hash is the check.
  const info = { hash, commit: gitCommit(moduleDir) };
  writeFileSync(path.join(moduleDir, BUILD_INFO_PATH),
    "// Generated by scripts/stamp-module.mjs — do not edit. Re-run it after changing module/.\n"
    + "// hash: SHA-256 over every file under module/ except this one and *.bak.\n"
    + `export const BUILD_INFO = ${JSON.stringify(info)};\n`);
  return { ...info, changed: true };
}

/** null when the stamp matches the tree, else a reason. */
export function checkStamp(moduleDir) {
  const stamp = readStamp(moduleDir);
  const hash = hashModuleTree(moduleDir);
  if (!stamp) return `${BUILD_INFO_PATH} is missing or unreadable`;
  if (stamp.hash !== hash) return `${BUILD_INFO_PATH} is stale (stamped ${stamp.hash.slice(0, 12)}, tree is ${hash.slice(0, 12)})`;
  return null;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes("--check")) {
    const problem = checkStamp(MODULE_DIR);
    if (problem) {
      console.error(`${problem}. Run: node scripts/stamp-module.mjs, then commit module/${BUILD_INFO_PATH}`);
      process.exit(1);
    }
    console.log(`module stamp is current: ${readStamp(MODULE_DIR).hash}`);
  } else {
    const { hash, commit, changed } = stampModule(MODULE_DIR);
    console.log(`${changed ? "stamped" : "unchanged"}: ${hash} (commit ${commit})`);
  }
}
